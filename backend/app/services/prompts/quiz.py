"""Промпты генерации теста.

Здесь только текст промптов: текст материала подставляет сервис, поэтому
шаблонных подстановок в строках нет — иначе фигурные скобки из материала
ломали бы форматирование. Числа вопросов подставляются в инструкцию, а не в
текст материала, поэтому f-строка здесь безопасна.
"""

QUIZ_SYSTEM_PROMPT = (
    "Ты — методист, который составляет проверочные тесты по учебным материалам. "
    "Опирайся только на текст, который прислал пользователь. Не добавляй факты, "
    "которых нет в тексте, и не используй внешние знания."
)

SUMMARY_INSTRUCTIONS = "Составь по этому материалу краткое содержание из 3–5 пунктов."

CHOICE_INSTRUCTIONS = (
    "Сгенерируй {count} тестовых вопросов: у каждого ровно 4 варианта ответа, "
    "верный ровно один — его индекс укажи в correct_index, а в поле kind поставь \"choice\"."
)

OPEN_INSTRUCTIONS = (
    "Сгенерируй {count} открытых вопросов: в поле kind поставь \"open\", "
    "а в reference — короткий эталонный ответ, по которому будет проверяться ответ студента."
)

CLOSING_INSTRUCTIONS = (
    "Вопросы должны проверять понимание содержания, а не память о формулировках. "
    "Пиши на русском языке."
)

MATERIAL_HEADER = "Текст материала:"


def build_quiz_instructions(choice_count: int, open_count: int) -> str:
    """Собирает инструкцию под запрошенный состав вопросов."""
    parts = [SUMMARY_INSTRUCTIONS]

    if choice_count > 0:
        parts.append(CHOICE_INSTRUCTIONS.format(count=choice_count))
    if open_count > 0:
        parts.append(OPEN_INSTRUCTIONS.format(count=open_count))

    parts.append(CLOSING_INSTRUCTIONS)
    return " ".join(parts)
